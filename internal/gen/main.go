// Command gen regenerates models_gen.go from https://tokport.io/api/models.
// Run it with `go generate ./...` from the module root.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"net/http"
	"os"
	"sort"
	"strings"
	"unicode"
)

func constName(id string) string {
	var b strings.Builder
	b.WriteString("Model")
	upper := true
	for _, r := range id {
		if r == '-' || r == '.' || r == '_' {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		b.WriteRune(r)
	}
	return b.String()
}

func main() {
	req, _ := http.NewRequest(http.MethodGet, "https://tokport.io/api/models", nil)
	req.Header.Set("User-Agent", "tokport-go-codegen")
	res, err := http.DefaultClient.Do(req)
	if err != nil {
		log.Fatal(err)
	}
	defer res.Body.Close()
	var body struct {
		Models []struct {
			ID, DisplayName, Modality, Status string
		} `json:"models"`
	}
	if err := json.NewDecoder(res.Body).Decode(&body); err != nil {
		log.Fatal(err)
	}
	models := body.Models[:0]
	for _, m := range body.Models {
		if m.Status == "active" {
			models = append(models, m)
		}
	}
	sort.Slice(models, func(i, j int) bool {
		if models[i].Modality != models[j].Modality {
			return models[i].Modality < models[j].Modality
		}
		return models[i].ID < models[j].ID
	})
	var out bytes.Buffer
	out.WriteString("// Code generated by internal/gen from https://tokport.io/api/models. DO NOT EDIT.\n\npackage tokport\n\n")
	out.WriteString("// Model ids live when this release was built. Any newer id from https://tokport.io/models works too.\nconst (\n")
	for _, m := range models {
		fmt.Fprintf(&out, "\t%s = %q // %s model\n", constName(m.ID), m.ID, m.Modality)
	}
	out.WriteString(")\n\n// ModelModality maps each known model id to \"image\" or \"video\".\nvar ModelModality = map[string]string{\n")
	for _, m := range models {
		fmt.Fprintf(&out, "\t%s: %q,\n", constName(m.ID), m.Modality)
	}
	out.WriteString("}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("models_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %d models to models_gen.go\n", len(models))
}
